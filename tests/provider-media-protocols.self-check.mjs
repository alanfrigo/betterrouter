import assert from "node:assert/strict";
import "./register-aliases.mjs";
const { buildClovaPayload } = await import("../open-sse/translator/request/openai-to-clova.js");
const { convertClovaToOpenAI } = await import("../open-sse/translator/response/clova-to-openai.js");
const { parseNovitaTaskResult } = await import("../open-sse/handlers/videoGeneration/novita.js");
const { buildXSearchRequest, extractXSearchHits } = await import("../open-sse/handlers/search/xSearch.js");
const { normalizeAnysearchSearchResponse } = await import("../open-sse/handlers/search/anysearchSearch.js");
const { isTwinmindAccessTokenFresh } = await import("../open-sse/services/twinmindAuth.js");

const payload=buildClovaPayload("HCX-007",{messages:[{role:"user",content:"weather"}],tools:[{type:"function",function:{name:"weather",parameters:{type:"object"}}}],max_tokens:1},true);
assert.equal(payload.thinking.effort,"none");
assert.equal(payload.maxCompletionTokens,1024);
const state={model:"HCX-007"};
const first=convertClovaToOpenAI('event: token\ndata: {"message":{"content":"hello"}}',state);
assert.equal(first.choices[0].delta.content,"hello");
const terminal=convertClovaToOpenAI('event: result\ndata: {"message":{"content":"hello"},"finishReason":"stop","usage":{"promptTokens":2,"completionTokens":1}}',state);
assert.equal(terminal.choices[0].delta.content,undefined);
assert.equal(terminal.usage.total_tokens,3);
convertClovaToOpenAI('event: error\ndata: {"status":{"code":"40001","message":"invalid"}}',state);
assert.equal(state.upstreamError.status,400);
const x=buildXSearchRequest({baseUrl:"https://api.x.ai/v1/responses"},{query:"news",maxResults:5,token:"key",domainFilter:["@example"]});
assert.equal(JSON.parse(x.init.body).tools[0].type,"x_search");
assert.deepEqual(JSON.parse(x.init.body).tools[0].allowed_x_handles,["example"]);
assert.equal(extractXSearchHits({citations:["https://x.com/example/status/123"]},"news",5)[0].author,"example");
assert.throws(()=>normalizeAnysearchSearchResponse({code:-1,message:"quota exhausted"},()=>{}));
assert.equal(parseNovitaTaskResult({task:{status:"TASK_STATUS_FAILED",reason:"quota"}}).done,true);
const jwt=exp=>`eyJhbGciOiJub25lIn0.${Buffer.from(JSON.stringify({exp})).toString("base64url")}.sig`;
assert.equal(isTwinmindAccessTokenFresh(jwt(400),100000),false);
assert.equal(isTwinmindAccessTokenFresh(jwt(401),100000),true);
console.log("Media protocol checks passed");
