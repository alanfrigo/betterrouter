export function resolvePublicCred(key, envName) {
  if (envName) {
    const fromEnv = process.env[envName];
    if (fromEnv && fromEnv.trim())
      return decodePublicCred(fromEnv.trim());
  }
  return decodePublicCredBytes(EMBEDDED_DEFAULTS[key]);
}
export function resolvePublicCredMulti(key, envNames) {
  for (const name of envNames) {
    const v = process.env[name];
    if (v && v.trim())
      return decodePublicCred(v.trim());
  }
  return decodePublicCredBytes(EMBEDDED_DEFAULTS[key]);
}
