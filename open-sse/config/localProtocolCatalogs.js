function model(id, name, maxOutputTokens, contextLength) {
    return {
        id,
        name,
        ...(maxOutputTokens === undefined ? {} : { maxOutputTokens }),
        ...(contextLength === undefined ? {} : { contextLength }),
    };
}
function effortModels(id, name, maxOutputTokens, contextLength, efforts = QUALITY_EFFORTS) {
    return efforts.map(([suffix, label]) => model(`${id}-${suffix}`, `${name} ${label}`, maxOutputTokens, contextLength));
}
